import Foundation

public enum NetworkResetError: Error, LocalizedError, Equatable {
    case cancelled
    case failed(String)

    public var errorDescription: String? {
        switch self {
        case .cancelled:
            return "Network reset was cancelled."
        case .failed(let detail):
            return "Network reset failed: \(detail)"
        }
    }
}

/// Resets macOS network settings that may have been left behind by an abnormal
/// VPN disconnect (e.g., sleep/wake hang, crash, or force-quit).
///
/// Clears lingering gpclient/gpauth processes, removes stale `scutil` Dynamic
/// Store entries for `utun` interfaces, restores `/etc/resolv.conf` if
/// generated by `vpnc-script`, removes stale `utun` default routes, resets
/// persistent DNS/search-domain overrides on enabled network services via
/// `networksetup`, flushes macOS DNS caches, and refreshes active interfaces so
/// macOS `configd` reasserts default routes, DNS, and internet reachability.
public enum NetworkResetter {
    public static let resetScript: String = #"""
    #!/bin/bash
    set -u

    echo "Stopping any lingering VPN processes..."
    pkill -INT -x gpclient 2>/dev/null || true
    pkill -INT -x gpauth 2>/dev/null || true
    sleep 1
    pkill -TERM -x gpclient 2>/dev/null || true
    pkill -TERM -x gpauth 2>/dev/null || true
    sleep 0.5
    pkill -KILL -x gpclient 2>/dev/null || true
    pkill -KILL -x gpauth 2>/dev/null || true

    echo "Removing stale scutil utun Dynamic Store entries..."
    UTUN_KEYS=$(printf 'list State:/Network/Service/utun.*\n' | scutil 2>/dev/null | awk '{print $NF}' | grep '^State:/Network/Service/utun' || true)
    if [ -n "$UTUN_KEYS" ]; then
      {
        echo "open"
        for key in $UTUN_KEYS; do
          echo "remove $key"
        done
        echo "close"
      } | scutil >/dev/null 2>&1 || true
      echo "Removed stale utun scutil keys."
    fi

    for key in $UTUN_KEYS; do
      dev=$(echo "$key" | awk -F'/' '{print $4}')
      if [ -n "$dev" ]; then
        ifconfig "$dev" down 2>/dev/null || true
      fi
    done

    DEF_IF=$(route -n get default 2>/dev/null | awk '/interface:/{print $2}' || true)
    case "$DEF_IF" in
      utun*)
        echo "Removing stale default route via $DEF_IF..."
        route -n delete default >/dev/null 2>&1 || true
        ;;
    esac

    if [ -f /etc/resolv.conf ] && grep -q '^#@VPNC_GENERATED@' /etc/resolv.conf 2>/dev/null; then
      BACKUP=$(ls -t /var/run/vpnc/resolv.conf-backup.* 2>/dev/null | head -n 1 || true)
      if [ -n "$BACKUP" ] && [ -f "$BACKUP" ]; then
        cat "$BACKUP" > /etc/resolv.conf 2>/dev/null || true
      else
        : > /etc/resolv.conf 2>/dev/null || true
      fi
      echo "Restored /etc/resolv.conf."
    fi

    for f in /var/run/vpnc/defaultroute.*; do
      [ -f "$f" ] || continue
      OLD_GW=$(cat "$f" 2>/dev/null || true)
      if [ -n "$OLD_GW" ]; then
        route -n delete default >/dev/null 2>&1 || true
        route -n add default "$OLD_GW" >/dev/null 2>&1 || true
      fi
    done
    rm -rf /var/run/vpnc 2>/dev/null || true

    echo "Resetting DNS and search domains on active network services..."
    while IFS= read -r service; do
      [ -z "$service" ] && continue
      case "$service" in
        "An asterisk"*|\**) continue ;;
      esac
      networksetup -setdnsservers "$service" Empty >/dev/null 2>&1 || true
      networksetup -setsearchdomains "$service" Empty >/dev/null 2>&1 || true
    done < <(networksetup -listallnetworkservices 2>/dev/null || true)

    echo "Flushing DNS cache and refreshing mDNSResponder..."
    dscacheutil -flushcache 2>/dev/null || true
    killall -HUP mDNSResponder 2>/dev/null || true

    echo "Refreshing active network interfaces..."
    while IFS= read -r line; do
      dev=$(echo "$line" | sed -n 's/.*Device: \([^)]*\)).*/\1/p')
      [ -z "$dev" ] && continue
      if ifconfig "$dev" 2>/dev/null | grep -q "status: active"; then
        svc=$(networksetup -listnetworkserviceorder 2>/dev/null | grep -B 1 "Device: $dev)" | head -n 1 | sed 's/^([0-9]*) //')
        case "$svc" in
          ""|\(*\)*) continue ;;
        esac
        info=$(networksetup -getinfo "$svc" 2>/dev/null || true)
        if echo "$info" | grep -q "^DHCP Configuration"; then
          echo "Renewing DHCP on $svc ($dev)..."
          ipconfig set "$dev" DHCP 2>/dev/null || true
        else
          echo "Refreshing $svc ($dev)..."
          networksetup -setnetworkserviceenabled "$svc" off 2>/dev/null || true
          sleep 0.5
          networksetup -setnetworkserviceenabled "$svc" on 2>/dev/null || true
        fi
      fi
    done < <(networksetup -listnetworkserviceorder 2>/dev/null || true)

    sleep 0.5
    dscacheutil -flushcache 2>/dev/null || true
    killall -HUP mDNSResponder 2>/dev/null || true

    echo "Network reset complete."
    exit 0
    """#

    /// Builds the `CommandLine` used by a root process (e.g. `OverlandHelper`)
    /// to execute the network reset directly.
    public static func rootCommand() -> CommandLine {
        CommandLine(executable: "/bin/bash", arguments: ["-c", resetScript])
    }

    /// Builds the `osascript` `CommandLine` for running the network reset with
    /// macOS's administrator authorization dialog (fallback when the privileged
    /// helper is unavailable).
    public static func adminPromptCommand() -> CommandLine {
        let encoded = Data(resetScript.utf8).base64EncodedString()
        let shCommand = "echo \(encoded) | /usr/bin/base64 -d | /bin/bash"
        let escaped = ShellQuoting.appleScript(shCommand)
        let script = "do shell script \"\(escaped)\" with administrator privileges with prompt \"Overland needs administrator privileges to reset macOS network and DNS settings.\""
        return CommandLine(executable: "/usr/bin/osascript", arguments: ["-e", script])
    }

    /// Runs the network reset directly (must already be running as root).
    public static func runAsRoot(
        using runner: any ProcessRunning = ProcessRunner(),
        onLine: (@Sendable (String) -> Void)? = nil
    ) async throws {
        let result = try await runner.run(rootCommand()) { _, line in
            onLine?(line)
        }
        if !result.isSuccess {
            let detail = result.stderr.trimmingCharacters(in: .whitespacesAndNewlines)
            throw NetworkResetError.failed(detail.isEmpty ? "exit code \(result.exitCode)" : detail)
        }
    }

    /// Runs the network reset via macOS's administrator privileges dialog.
    public static func runWithAdminPrompt(
        using runner: any ProcessRunning = ProcessRunner(),
        onLine: (@Sendable (String) -> Void)? = nil
    ) async throws {
        let result = try await runner.run(adminPromptCommand()) { _, line in
            onLine?(line)
        }
        if !result.isSuccess {
            let detail = result.stderr.trimmingCharacters(in: .whitespacesAndNewlines)
            if detail.contains("-128") || detail.localizedCaseInsensitiveContains("User canceled") {
                throw NetworkResetError.cancelled
            }
            throw NetworkResetError.failed(detail.isEmpty ? "exit code \(result.exitCode)" : detail)
        }
    }
}
